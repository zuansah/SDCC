export const handlers = {
  get_ticket: async (args: any, context: ToolExecutionContext) => {
    const term = (args.numberOrId || '').trim().toLowerCase();
    const ctrl = context.sharedData?.controllersPayload;
    const intel = context.sharedData?.intelligencePayload;
    const tickets = ctrl?.tickets || [];

    const found = tickets.find((t: any) =>
      (t.number || '').toLowerCase() === term ||
      (t.id || '').toLowerCase() === term ||
      (t.serial || '').toLowerCase() === term
    );

    if (!found) {
      return { error: `Ticket '${args.numberOrId}' not found in active operational feeds.` };
    }

    // Lookup triage verdict
    const triage = intel?.openTicketTriage?.find((tr: any) =>
      (tr.ticketNumber && tr.ticketNumber.toLowerCase() === term) ||
      (tr.serial && tr.serial.toLowerCase() === (found.serial || '').toLowerCase())
    );

    return {
      number: found.number || '—',
      faultId: found.id,
      type: found.type || (found.number?.startsWith('DWN') ? 'Down' : 'Proactive'),
      site: found.site || found.name,
      tenant: found.tenant || 'Telkom Customer',
      serial: found.serial || '—',
      status: found.status || 'OPEN',
      openedAt: found.createdAt || found.openedAt || 'Today 08:30 WIB',
      duration: found.duration || '2h 15m',
      aiTriage: {
        verdict: triage?.triage || 'NEEDS_ATTENTION',
        reason: triage?.reason || 'Requires operational investigation.',
        willAutoClear: triage?.triage === 'LIKELY_SCHEDULED',
      },
    };
  },

  list_tickets: async (args: any, context: ToolExecutionContext) => {
    const ctrl = context.sharedData?.controllersPayload;
    const intel = context.sharedData?.intelligencePayload;
    const tickets = ctrl?.tickets || [];
    let filtered = [...tickets];

    if (args.type && args.type !== 'all') {
      const ty = args.type.toLowerCase();
      filtered = filtered.filter((t: any) => (t.type || '').toLowerCase().includes(ty));
    }

    if (args.tenant) {
      const tn = args.tenant.toLowerCase();
      filtered = filtered.filter((t: any) => (t.tenant || '').toLowerCase().includes(tn));
    }

    if (args.triage && args.triage !== 'ALL') {
      filtered = filtered.filter((t: any) => {
        const tr = intel?.openTicketTriage?.find((item: any) =>
          item.serial === t.serial || item.ticketNumber === t.number
        );
        return tr ? tr.triage === args.triage : args.triage === 'NEEDS_ATTENTION';
      });
    }

    const total = filtered.length;
    const capped = filtered.slice(0, 25).map((t: any) => {
      const tr = intel?.openTicketTriage?.find((item: any) =>
        item.serial === t.serial || item.ticketNumber === t.number
      );
      return {
        number: t.number || t.id,
        faultId: t.id,
        type: t.type || (t.number?.startsWith('DWN') ? 'Down' : 'Proactive'),
        site: t.site || t.name,
        tenant: t.tenant || '—',
        serial: t.serial || '—',
        status: t.status || 'OPEN',
        triage: tr?.triage || 'NEEDS_ATTENTION',
        triageReason: tr?.reason || 'Normal alarm investigation',
      };
    });

    return { total, count: capped.length, tickets: capped };
  },

  ticket_stats: async (args: any, context: ToolExecutionContext) => {
    const ctrl = context.sharedData?.controllersPayload;
    const intel = context.sharedData?.intelligencePayload;
    const tickets = ctrl?.tickets || [];
    const groupBy = args.groupBy || 'type';
    const counts: Record<string, number> = {};

    tickets.forEach((t: any) => {
      let key = 'Other';
      if (groupBy === 'type') key = t.type || 'Unknown';
      else if (groupBy === 'tenant') key = t.tenant || 'Unassigned';
      else if (groupBy === 'status') key = t.status || 'OPEN';
      else if (groupBy === 'triage') {
        const tr = intel?.openTicketTriage?.find((item: any) => item.serial === t.serial);
        key = tr ? tr.triage : 'NEEDS_ATTENTION';
      }
      counts[key] = (counts[key] || 0) + 1;
    });

    return { totalTickets: tickets.length, groupBy, breakdown: counts };
  },

  propose_assurance_ticket: async (args: any, context: ToolExecutionContext) => {
    const cardId = context.proposeAction({
      type: 'assurance_ticket',
      title: `Create Assurance Ticket: ${args.siteName}`,
      description: `Create human-authored InSERA/Assurance ticket for ${args.customer} (${args.issueDescription})`,
      payload: {
        sid: args.sid || '—',
        siteName: args.siteName,
        customer: args.customer,
        issue: args.issueDescription,
        contact: args.contactPerson || '—',
        priority: args.priority || 'P2',
      },
    });

    return {
      status: 'proposed',
      actionId: cardId,
      action: 'assurance_ticket',
      message: `Proposed Assurance ticket for ${args.siteName}. Confirm in the card to execute.`,
    };
  },

  propose_close_assurance_ticket: async (args: any, context: ToolExecutionContext) => {
    const cardId = context.proposeAction({
      type: 'close_assurance_ticket',
      title: `Resolve Assurance Ticket: ${args.ticketId}`,
      description: `Mark ticket as RESOLVED with note: "${args.resolutionNote}"`,
      payload: {
        ticketId: args.ticketId,
        resolutionNote: args.resolutionNote,
      },
    });

    return {
      status: 'proposed',
      actionId: cardId,
      action: 'close_assurance_ticket',
      message: `Proposed closing Assurance ticket ${args.ticketId}. Confirm in the card to execute.`,
    };
  },
};
